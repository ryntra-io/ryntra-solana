/** A word of the section, with `{x}`-style places filled in. */
export function earnWord(locale: "en" | "uk", key: EarnWordKey, fill: Readonly<Record<string, string>> = {}): string {
  return EARN_WORDS[locale][key].replace(/\{(\w+)\}/g, (whole, name: string) => fill[name] ?? whole);
}

/** The word for a failure code, and one honest line for anything this page has never seen. */
export function earnFailureWord(locale: "en" | "uk", code: string): string {
  const key = `fail.${code}` as EarnWordKey;
  return key in EARN_WORDS[locale] ? earnWord(locale, key) : earnWord(locale, "fail.general");
}
