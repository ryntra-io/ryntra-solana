/** A word of the orders, with its blanks filled in. */
export function orderWord(locale: "en" | "uk", key: OrderWordKey, fill: Readonly<Record<string, string>> = {}): string {
  return ORDER_WORDS[locale][key].replace(/\{(\w+)\}/g, (whole, name: string) => fill[name] ?? whole);
}

const KNOWN_FAILURES: ReadonlySet<string> = new Set(Object.keys(ORDER_WORDS.en).filter((key) => key.startsWith("fail.")).map((key) => key.slice(5)));

/** A refusal's code in the person's words; a code this page does not know is the general line. */
export function orderFailure(locale: "en" | "uk", code: string): string {
  return orderWord(locale, (KNOWN_FAILURES.has(code) && code !== "general" ? `fail.${code}` : "fail.general") as OrderWordKey);
}
