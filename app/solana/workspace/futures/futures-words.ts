/** A word of the page, with `{x}`, `{s}` and `{coin}` filled in. */
export function futuresWord(locale: "en" | "uk", key: FuturesWordKey, fill: Readonly<Record<string, string>> = {}): string {
  return FUTURES_WORDS[locale][key].replace(/\{(\w+)\}/g, (whole, name: string) => fill[name] ?? whole);
}

/** Phoenix's own words that reach the page — a session's state, an order's type — in the page's language; any other word as Phoenix wrote it. */
