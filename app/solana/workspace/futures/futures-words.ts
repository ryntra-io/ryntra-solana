  limit: { en: "Limit", uk: "Ліміт" },
  market: { en: "Market", uk: "Ринковий" },
  postonly: { en: "Post-only", uk: "Лише мейкер" },
  stoploss: { en: "Stop-loss", uk: "Стоп-лос" },
  takeprofit: { en: "Take-profit", uk: "Тейк-профіт" },
  immediateorcancel: { en: "IOC", uk: "IOC" },
