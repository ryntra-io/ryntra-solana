export function issueWord(locale: WorkspaceLocale, issue: Readonly<{ code: TreasuryIssueCode; line?: number; at?: string }>): string {
  const at = issue.at ?? "";
  return ISSUE_WORDS[issue.code][locale].replace("{line}", String(issue.line ?? "")).replace("{at}", at.length > 12 ? `${at.slice(0, 4)}…${at.slice(-4)}` : at);
}
