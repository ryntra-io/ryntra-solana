/** `on 6 venues` / `на 6 майданчиках`. */
export function onVenues(n: number, locale: WorkspaceLocale): string {
  if (locale === "uk") return `на ${n} ${n % 10 === 1 && n % 100 !== 11 ? "майданчику" : "майданчиках"}`;
  return `on ${n} ${n === 1 ? "venue" : "venues"}`;
}

/** The ticket's promise: `Buy $10 — if «Yes», you get ≈ $12.20`. */
export function payoffSentence(amount: string, outcome: string, payout: string, locale: WorkspaceLocale): string {
  if (locale === "uk") return `Купуєш на ${amount} — якщо «${outcome}», отримаєш ≈ ${payout}`;
  return `Buy ${amount} — if “${outcome}”, you get ≈ ${payout}`;
}

/**
 * The line under the payout: what is lost if the chosen outcome does not
 * come true — the whole amount. On a Yes/No market it names the other side.
 */
export function lossSentence(amount: string, other: string | null, locale: WorkspaceLocale): string {
  if (locale === "uk") return other ? `Якщо «${other}» — втрачаєш ${amount} (усю суму)` : `Якщо ні — втрачаєш ${amount} (усю суму)`;
  return other ? `If “${other}”: you lose ${amount} (the whole amount)` : `If not: you lose ${amount} (the whole amount)`;
}

