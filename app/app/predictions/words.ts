/** A venue's Yes/No in the person's language; any other label is the venue's own word. */
export function outcomeLabel(label: string, locale: WorkspaceLocale): string {
  if (locale !== "uk") return label;
  if (/^yes$/i.test(label)) return "Так";
  if (/^no$/i.test(label)) return "Ні";
  return label;
}

