/** `Venues settle this market differently in 3 ways.` / `Майданчики розраховують цей ринок по-різному: 3 відмінності.` */
export function catchLead(n: number, locale: WorkspaceLocale): string {
  if (locale === "uk") {
    const m10 = n % 10;
    const m100 = n % 100;
    const noun = m10 === 1 && m100 !== 11 ? "відмінність" : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? "відмінності" : "відмінностей";
    return `Майданчики розраховують цей ринок по-різному: ${n} ${noun}.`;
  }
  return `Venues settle this market differently in ${n} ${n === 1 ? "way" : "ways"}.`;
}

