/** A linked market closes before or after this one: `Closes 12 days before this one…` / `Закривається на 12 днів раніше за цей…`. */
export function mapCloseSentence(days: number, when: "before" | "after", locale: WorkspaceLocale): string {
  if (locale === "uk") {
    const noun = daysNoun(days);
    return when === "before"
      ? `Закривається на ${days} ${noun} раніше за цей: далі цей ринок лишається без пари.`
      : `Закривається на ${days} ${noun} пізніше за цей: коли цей ринок отримає результат, той ще торгуватиметься.`;
  }
  const noun = days === 1 ? "day" : "days";
  return when === "before" ? `Closes ${days} ${noun} before this one: after that, this market stands alone.` : `Closes ${days} ${noun} after this one: when this one settles, that one still trades.`;
}

/** The short tag of a market closing earlier: `Closes 7d earlier` / `Закривається на 7 дн. раніше`. */
export function mapEarlierTag(days: number, locale: WorkspaceLocale): string {
  return locale === "uk" ? `Закривається на ${days} дн. раніше` : `Closes ${days}d earlier`;
}

function daysNoun(n: number): string {
  const m10 = n % 10;
  const m100 = n % 100;
  return m10 === 1 && m100 !== 11 ? "день" : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? "дні" : "днів";
}

/** A limit order's state as a person reads it: accepted, partly filled, filled, cancelled, lapsed. */
export function limitStateWord(state: LimitOrderState, word: (key: PredictionWord) => string): string {
  switch (state) {
    case "sending":
      return word("limitSending");
    case "accepted":
      return word("limitAccepted");
    case "partially_filled":
      return word("limitPartly");
    case "filled":
      return word("filled");
    case "cancelled":
      return word("cancelled");
    case "expired":
      return word("limitLapsed");
    case "failed":
      return word("limitNotPlaced");
    default:
      return word("limitReview");
  }
}

export function limitTone(state: LimitOrderState): "good" | "wait" | "bad" | undefined {
  if (state === "filled") return "good";
  if (state === "sending" || state === "accepted" || state === "partially_filled") return "wait";
  if (state === "cancelled" || state === "expired" || state === "failed") return "bad";
  return undefined;
}
