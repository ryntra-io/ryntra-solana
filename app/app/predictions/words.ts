export type PredictionWord = keyof typeof EN;

export function wordsFor(locale: WorkspaceLocale): (key: PredictionWord) => string {
  const table = locale === "uk" ? UK : EN;
  return (key) => table[key];
}

/** The provider's category slugs in the person's language; a slug without a word is shown as the provider names it. */
