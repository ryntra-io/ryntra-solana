export type LaunchWordKey = keyof typeof LAUNCH_WORDS;

export function launchWords(locale: WorkspaceLocale) {
  return (key: LaunchWordKey, values: Readonly<Record<string, string | number>> = {}) =>
    LAUNCH_WORDS[key][locale].replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
}
