export type ConstitutionWordKey = keyof typeof CONSTITUTION_WORDS;

export function constitutionWords(locale: WorkspaceLocale) {
  return (key: ConstitutionWordKey, values: Readonly<Record<string, string | number>> = {}) =>
    CONSTITUTION_WORDS[key][locale].replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
}

/** Whether a word exists for a key built from the document — a field, a code, a reason. */
export function hasConstitutionWord(key: string): key is ConstitutionWordKey {
  return Object.prototype.hasOwnProperty.call(CONSTITUTION_WORDS, key);
}
