export function getLabCopy(locale: LocaleCode): LabCopy {
  if (locale === 'ar') return { ...LAB_EN, ...CORE.ar, ...AR_CRITICAL };
  if (locale === "en") return LAB_EN;
  if (locale === "uk") return { ...LAB_EN, ...UK };
  if (locale === "ru") return { ...LAB_EN, ...RU };
  return { ...LAB_EN, ...CORE[locale] };
}

export type LabApiErrorPayload = {
  error?: unknown;
  issues?: unknown;
};

export function getLabApiError(
  locale: LocaleCode,
  payload: LabApiErrorPayload,
  fallback: string,
): string {
  const copy = getLabCopy(locale);
  const code = typeof payload.error === 'string' ? payload.error.toLowerCase() : '';
  const base = (() => {
    if (code === 'unauthorized' || code === 'not verified' || code === 'cross-site request blocked') return copy.authRequired;
    if (code === 'rate limited') return copy.rateLimited;
    if (code === 'request too large' || code === 'file-too-large') return copy.fileTooLarge;
    if (code === 'invalid request' || code === 'invalid-request') return copy.invalidRequest;
    if (code === 'invalid strategy' || code === 'invalid strategy version') return copy.invalidStrategy;
    if (code === 'file-hash-mismatch') return copy.fileHashMismatch;
    if (code === 'unsupported-trades-format') return copy.unsupportedTrades;
    if (code === 'unsupported-performance-format') return copy.unsupportedPerformance;
    if (code === 'manifest-strategy-mismatch') return copy.strategyMismatch;
    if (code === 'invalid trade data') return copy.invalidTradeData;
    if (code === 'evidence proof unavailable') return copy.proofUnavailable;
    if (code === 'invalid evidence proof') return copy.invalidProof;
    if (code === 'version mismatch') return copy.versionMismatch;
    if (code === 'approval unavailable') return copy.approvalUnavailable;
    if (code === 'invalid approval' || code === 'invalid parent approval') return copy.approvalInvalid;
    if (code === 'ai-unavailable') return copy.aiUnavailable;
    if (code === 'ai-refused') return copy.aiRefused;
    if (code === 'ai-timeout') return copy.aiTimeout;
    if (code === 'ai-quota') return copy.aiQuota;
    if (code === 'ai-rate-limited') return copy.aiRateLimited;
    if (code === 'ai-in-flight') return copy.aiInFlight;
    if (code === 'ai-global-in-flight') return copy.aiGlobalInFlight;
    if (code === 'ai-local-user-budget') return copy.aiLocalUserBudget;
    if (code === 'ai-local-global-budget') return copy.aiLocalGlobalBudget;
    if (code === 'ai-idempotency-conflict') return copy.aiIdempotencyConflict;
    if (code === 'invalid-ai-output') return copy.invalidAiOutput;
    if (code === 'invalid-proposal' || code === 'unsupported-change') return copy.invalidDraft;
    return fallback;
  })();
  const issue = Array.isArray(payload.issues)
    ? payload.issues.find((item) => item && typeof item === 'object' && typeof (item as { message?: unknown }).message === 'string') as { path?: unknown; message?: string } | undefined
    : undefined;
  if (!issue?.message) return base;
  const path = typeof issue.path === 'string' && issue.path ? `${issue.path}: ` : '';
  return `${base} ${path}${issue.message}`;
}
