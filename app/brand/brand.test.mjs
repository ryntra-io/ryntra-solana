// Run from repo root: node --test app/brand/brand.test.mjs
//
// The brand rules, enforced — the palette of 2026-09-11 with the flat masters
// of 2026-09-13: one official mark, the orange R traced from the flat master
// into app/brand/mark.ts; one wordmark [R]YNTRA on every header and footer;
// the same R on the dark tile as the favicon. The site once carried four
// hand-drawn logos at the same time; these tests are what keeps a fifth from
// appearing.
import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import test from "node:test";

import { R_MARK_MATERIAL, R_MARK_PATHS, R_MARK_SOURCE, R_MARK_TRACE, RYNTRA_COLORS, RYNTRA_GRADIENT } from "./mark.ts";
import { needsDevelopmentRepository } from "../../lib/development-repository.mjs";

const read = (path) => readFileSync(new URL("../../" + path, import.meta.url), "utf8");
const exists = (path) => existsSync(new URL("../../" + path, import.meta.url));

test("the canonical mark is the traced geometry with the master's own ramp", { skip: needsDevelopmentRepository("the traced brand geometry under scripts/brand/") }, () => {
  // Two subpaths: stem+bar, arrow+leg. A changed count means someone redrew
  // the mark rather than re-tracing it.
  assert.equal((R_MARK_PATHS.match(/M/g) ?? []).length, 2);
  /* The geometry is a measurement of the flat master, and the trace reports
     how much of the master it covers. Anything under 99% is a
     different letter; the render script refuses to write it and this pin
     refuses to ship it. */
  assert.equal(R_MARK_SOURCE, "LOGO/Брендбук2/Лого.png");
  assert.ok(R_MARK_TRACE.fidelity >= 0.99, `mark trace fidelity ${R_MARK_TRACE.fidelity}`);
  assert.equal(R_MARK_TRACE.points.length, 2, "the trace reports its two rings");
  const trace = JSON.parse(read("scripts/brand/mark-trace.json"));
  assert.equal(trace.path, R_MARK_PATHS, "the geometry module is drawn from the trace");
  assert.equal(trace.source, R_MARK_SOURCE);
  /* The material is the master's ramp, read from its interior — six stops
     from the top-left light to the bottom-right deep — never a hand-picked
     pair. The two-stop alias is its two ends. */
  assert.equal(R_MARK_MATERIAL.length, 6);
  for (const [color, offset] of R_MARK_MATERIAL) {
    assert.match(color, /^#[0-9A-F]{6}$/, "material stops are upper-case hex");
    assert.ok(offset >= 0 && offset <= 1);
  }
  assert.equal(R_MARK_MATERIAL[0][1], 0);
  assert.equal(R_MARK_MATERIAL[R_MARK_MATERIAL.length - 1][1], 1);
  assert.equal(RYNTRA_GRADIENT.from, R_MARK_MATERIAL[0][0]);
  assert.equal(RYNTRA_GRADIENT.to, R_MARK_MATERIAL[R_MARK_MATERIAL.length - 1][0]);
  assert.equal(RYNTRA_COLORS.orange, "#FF681C");
  assert.equal(RYNTRA_COLORS.graphite, "#080D13");
  assert.equal(RYNTRA_COLORS.heat, RYNTRA_COLORS.orange, "the legacy alias resolves to the brand orange");

  const component = read("app/brand/ryntra-brand.tsx");
  assert.match(component, /R_MARK_PATHS/, "the component must render the canonical paths");
  assert.match(component, /R_MARK_MATERIAL_AXIS/, "the component draws the ramp along the master's axis");
  assert.match(component, /R_MARK_MATERIAL\.map/, "the component draws every stop of the material");
  assert.match(component, /className="ryntra-brand" role="img" aria-label="Ryntra"/);
  /* The mark IS the R, and the YNTRA letterforms are drawn rather than set.
     Typesetting them in a UI face renders a different logo, so the lockup
     ships as the traced artwork and no face may stand in. */
  assert.match(component, /ryntra-wordmark-dark\.svg/, "the lockup uses the official dark wordmark");
  assert.match(component, /ryntra-wordmark-light\.svg/, "the lockup uses the official light wordmark");
  assert.doesNotMatch(component, />\s*R?YNTRA\s*</, "the wordmark is artwork, never set type");
  assert.doesNotMatch(
    component,
    /d="M(?!\{)/,
    "the component may not carry path data of its own",
  );
});

