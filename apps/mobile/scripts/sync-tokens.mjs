#!/usr/bin/env node
/**
 * Copies the core's design tokens (task A2) and its menu (Menu 3) into the app, from the newest core archive on
 * `origin/master` — `vendor/ryntra-core/*.tgz`, the archive line A ships to its own apps, or
 * `vendor/ryntra-core-next/*.tgz`, a newer one waiting for its apps to take it:
 * - `tokens/tokens.json` becomes `src/theme/core-tokens.json` byte for byte, and `src/theme/core-tokens.ts` its typed
 *   projection;
 * - `dist/ui/nav.js` (`@ryntra/core/nav`, pure data and words) becomes `src/features/shell/core-nav.ts` — the
 *   groups, their rows, the phone's bar, Money's four actions and the words, so the phone draws the web's menu.
 * `--check` exits non-zero when a file is not what the archive would give; `--from <tokens.json>` reads a checkout of
 * the core's tokens instead (the same file, before line A vendors it) and leaves the menu alone.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import { renderCoreTokensTs } from '../src/theme/render-core.mjs'
import { newestCoreArchive, tarEntry } from './core-archive.mjs'

const jsonTarget = fileURLToPath(new URL('../src/theme/core-tokens.json', import.meta.url))
const tsTarget = fileURLToPath(new URL('../src/theme/core-tokens.ts', import.meta.url))
const navTarget = fileURLToPath(new URL('../src/features/shell/core-nav.ts', import.meta.url))
const args = process.argv.slice(2)
const check = args.includes('--check')
const fromIndex = args.indexOf('--from')

function fromArchive() {
  const { source, name, tar } = newestCoreArchive()
  const tokens = tarEntry(tar, 'package/tokens/tokens.json')
  if (!tokens) throw new Error(`${name} has no package/tokens/tokens.json`)
  const nav = tarEntry(tar, 'package/dist/ui/nav.js')
  if (!nav) throw new Error(`${name} has no package/dist/ui/nav.js — the menu needs core 0.4.0 or newer`)
  return { source, json: tokens.toString('utf8'), nav: nav.toString('utf8') }
}

/** The menu as data: the core's module is pure (no imports), so it is evaluated as it ships and its values kept. */
async function renderNav(code, source) {
  const nav = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`)
  const data = {
    home: nav.NAV_HOME,
    groups: nav.NAV_GROUPS,
    defaultOpen: nav.NAV_DEFAULT_OPEN,
    phoneBar: nav.PHONE_BAR,
    moneyActions: nav.MONEY_ACTIONS,
    words: nav.NAV_WORDS,
  }
  for (const [key, value] of Object.entries(data)) if (value === undefined) throw new Error(`nav.js has no ${key}`)
  return [
    '/**',
    " * GENERATED by scripts/sync-tokens.mjs from the core's dist/ui/nav.js (`@ryntra/core/nav`) — never edit by hand.",
    ` * Source: ${source}`,
    ' */',
    `export const coreNav = ${JSON.stringify(data, null, 2)} as const`,
    '',
  ].join('\n')
}

const { source, json, nav } =
  fromIndex >= 0
    ? { source: args[fromIndex + 1], json: readFileSync(args[fromIndex + 1], 'utf8'), nav: null }
    : fromArchive()
const expectedJson = json.replace(/\r\n/g, '\n')
const expectedTs = renderCoreTokensTs(JSON.parse(expectedJson), source.replace(/\\/g, '/'))
const expectedNav = nav === null ? null : await renderNav(nav, source.replace(/\\/g, '/'))

if (check) {
  const read = (path) => {
    try {
      return readFileSync(path, 'utf8').replace(/\r\n/g, '\n')
    } catch {
      return ''
    }
  }
  const stale = []
  if (read(jsonTarget) !== expectedJson) stale.push('src/theme/core-tokens.json')
  // The header names the source; the values are what must agree.
  const body = (text) =>
    text
      .split('\n')
      .filter((line) => !line.startsWith(' * Source:'))
      .join('\n')
  if (body(read(tsTarget)) !== body(expectedTs)) stale.push('src/theme/core-tokens.ts')
  if (expectedNav !== null && body(read(navTarget)) !== body(expectedNav)) stale.push('src/features/shell/core-nav.ts')
  if (stale.length) {
    console.error(`${stale.join(', ')} differ from ${source} — run \`node scripts/sync-tokens.mjs\`.`)
    process.exit(1)
  }
  console.log(`core tokens${expectedNav === null ? '' : ' and menu'} match ${source}`)
} else {
  writeFileSync(jsonTarget, expectedJson)
  writeFileSync(tsTarget, expectedTs)
  if (expectedNav !== null) writeFileSync(navTarget, expectedNav)
  console.log(`wrote core-tokens.json, core-tokens.ts${expectedNav === null ? '' : ' and core-nav.ts'} from ${source}`)
}
