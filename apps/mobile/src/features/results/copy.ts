/** A reminder as it stands now — `ShownState` of `results-model.ts`. */
type Shown = 'open' | 'deferred' | 'pending' | 'paused' | 'bought' | 'missed' | 'held' | 'priceHeld'

/** One, few, many — the Ukrainian count forms. */
function uk(n: number, one: string, few: string, many: string): string {
  const tens = n % 100
  const last = n % 10
  if (last === 1 && tens !== 11) return one
  if (last >= 2 && last <= 4 && (tens < 10 || tens >= 20)) return few
  return many
}

