/**
 * The words of «Стежу» and «Доручення» in both languages — the chrome around the server's own texts (a rule as the
 * server words it, a preset's name, a task's name and rhythm, an alert's title). Wording follows the web's own words
 * for the same surfaces, so a person who knows one reads the other.
 */
/** «до 2 кредитів», «до 1 кредиту» — after «до» the count takes the genitive; a dash while the price is not read. */
function upToUk(count: number | null): string {
  if (count === null) return DASH
  const one = count % 10 === 1 && count % 100 !== 11
  return `до ${formatCount(count, 'uk')} ${one ? 'кредиту' : 'кредитів'}`
}

function capital(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1)
}

function upToEn(count: number | null): string {
  if (count === null) return DASH
  return `up to ${formatCount(count, 'en')} ${count === 1 ? 'credit' : 'credits'}`
}

