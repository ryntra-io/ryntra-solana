type Words<T> = {
  readonly [K in keyof T]: T[K] extends (...args: infer A) => string
    ? (...args: A) => string
    : T[K] extends readonly string[]
      ? readonly string[]
      : T[K] extends Record<string, string>
        ? Readonly<Record<keyof T[K], string>>
        : string
}

