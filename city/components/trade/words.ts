/** The engine's risk verdict over an order in the card's words; a verdict the card does not know stays as written. */
export function riskWords(verdict: string, w: Readonly<{ noBlocker: string; needsCare: string; blocked: string; notFullyRead: string }>): string {
  if (verdict === 'NO_KNOWN_BLOCKER') return w.noBlocker;
  if (verdict === 'REVIEW_REQUIRED') return w.needsCare;
  if (verdict === 'BLOCKED') return w.blocked;
  if (verdict === 'INCOMPLETE') return w.notFullyRead;
  return verdict;
}

