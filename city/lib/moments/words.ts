const MONTH_UK: Readonly<Record<string, string>> = {
  JAN: 'СІЧ',
  FEB: 'ЛЮТ',
  MAR: 'БЕР',
  APR: 'КВІ',
  MAY: 'ТРА',
  JUN: 'ЧЕР',
  JUL: 'ЛИП',
  AUG: 'СЕР',
  SEP: 'ВЕР',
  OCT: 'ЖОВ',
  NOV: 'ЛИС',
  DEC: 'ГРУ',
};
const WINDOW_UK: Readonly<Record<string, string>> = { '5M': '5 ХВ', '1H': '1 ГОД', '24H': '24 ГОД', '7D': '7 ДН' };

/**
 * A moment's kicker, title and figure are written once, in English (`moment.ts`): the clip and the card for X carry
 * them so. The city's list and share sheet retell them in the language on screen. Each rule is one fixed phrase of
 * moment.ts; a phrase no rule knows (a ticker, a studio post) stays as it was written.
 */
const RETELL_UK: readonly (readonly [RegExp, string | ((...m: string[]) => string)])[] = [
  [/^LAUNCH DOCKS$/, 'ДОКИ ЛАУНЧУ'],
  [/^DISTRICT WAR$/, 'ВІЙНА РАЙОНІВ'],
  [/^GRADUATED$/, 'ВИПУСК'],
  [/^SURVIVED DAY (\d+)$/, (_, d) => `ВИСТОЯЛА ${d} ${pl(Number(d), 'ДЕНЬ', 'ДНІ', 'ДНІВ')}`],
  [/^BIG X$/, 'ВЕЛИКИЙ ІКС'],
  [/^NEW RECORD$/, 'НОВИЙ РЕКОРД'],
  [/^NEW TOWER$/, 'НОВА ВЕЖА'],
  [/^A RYNTRA LAUNCH$/, 'ЛАУНЧ RYNTRA'],
  [/^([\d.]+) S$/, (_, t) => `${t} С`],
  [/^NEW POOL · (.+) CAP$/, (_, v) => `НОВИЙ ПУЛ · КАПІТАЛІЗАЦІЯ ${v}`],
  [/^UNVERIFIED · NEW POOL$/, 'НЕ ПЕРЕВІРЕНО · НОВИЙ ПУЛ'],
  [/^NEW POOL$/, 'НОВИЙ ПУЛ'],
  [/^WON THE WEEK · (.+) VERIFIED ACTIONS$/, (_, n) => `ВИГРАВ ТИЖДЕНЬ · ${n} ПЕРЕВІРЕНИХ ДІЙ`],
  [/^WON THE WEEK$/, 'ВИГРАВ ТИЖДЕНЬ'],
  [/^LAUNCHED ON RYNTRA · METEORA CURVE$/, 'ЗАПУЩЕНО НА RYNTRA · КРИВА METEORA'],
  [/^PAST \$75K ON THE CURVE · NOW A DAMM V2 POOL$/, 'ПОНАД $75K НА КРИВІЙ · ТЕПЕР ПУЛ DAMM V2'],
  [/^(.+) HOLDERS · DAY (\d+) CHECK$/, (_, n, d) => `${n} ХОЛДЕРІВ · ПЕРЕВІРКА ${d}-ГО ДНЯ`],
  [/^DAY (\d+) CHECK · ON CHAIN$/, (_, d) => `ПЕРЕВІРКА ${d}-ГО ДНЯ · ОНЧЕЙН`],
  [/^(\S+X) · ENTRY TO EXIT · ON CHAIN$/, (_, x) => `${x} · ВІД ВХОДУ ДО ВИХОДУ · ОНЧЕЙН`],
  [/^([+−-][\d.]+%) · (5M|1H|24H|7D) · (.+)$/, (_, move, win, rule) => `${move} · ${WINDOW_UK[win] ?? win} · ${rule}`],
  [/^([A-Z]{3}) (\d+) COURSE · (FLIGHT|ROOFTOPS)$/, (_, mon, d, form) => `ТРАСА ${d} ${MONTH_UK[mon] ?? mon} · ${form === 'FLIGHT' ? 'ПОЛІТ' : 'ДАХИ'}`],
  [/^(.+) FOUND$/, (_, agent) => `${agent} ЗНАЙШОВ`],
];

/** One of a moment's lines, in the language given («uk» retells it; English is how it was written). */
export function retellMoment(text: string, lang: 'en' | 'uk'): string {
  if (lang === 'en' || !text) return text;
  for (const [rule, to] of RETELL_UK) {
    const m = text.match(rule);
    if (m) return digits(typeof to === 'string' ? to : to(...m), lang);
  }
  return digits(text, lang);
}
