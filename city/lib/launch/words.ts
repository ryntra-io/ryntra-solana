/**
 * A launch's moment is written once in English (`moments.ts`, `district.ts`): the X drafts match those words. The
 * city's cut-in retells it in the language on screen; a line no entry knows stays as it was written.
 */
export function retellLaunchMoment(text: string, lang: 'en' | 'uk'): string | null {
  const en = LAUNCH_MOMENTS.en;
  const to = LAUNCH_MOMENTS[lang];
  for (const key of Object.keys(en) as (keyof typeof en)[]) {
    const word = en[key];
    if (typeof word === 'string' && word === text) return to[key] as string;
  }
  let m = /^(\d+)% TO THE SKYLINE$/.exec(text);
  if (m) return to.toSkyline(Number(m[1]));
  m = /^(.+) · POOL OPEN$/.exec(text);
  if (m) return to.poolOpenAt(m[1]!);
  m = /^Day (\d+) check$/.exec(text);
  if (m) return to.check(Number(m[1]));
  return null;
}


