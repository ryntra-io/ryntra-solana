/** «N coins», as Ukrainian counts them: 1 монету, 2–4 монети, 5 монет (11–14 — монет). */
function coinsUk(n: number): string {
  const ten = n % 10;
  const hundred = n % 100;
  if (ten === 1 && hundred !== 11) return 'монету';
  if (ten >= 2 && ten <= 4 && (hundred < 12 || hundred > 14)) return 'монети';
  return 'монет';
}

