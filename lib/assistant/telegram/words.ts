export type TgLocale = "uk" | "en";

/** «1 кредит», «2 кредити», «5 кредитів»; «1 credit», «2 credits». */
export function credits(locale: TgLocale, n: number): string {
  if (locale === "en") return `${n} ${n === 1 ? "credit" : "credits"}`;
  const tens = n % 100;
  const ones = n % 10;
  const word = tens >= 11 && tens <= 14 ? "кредитів" : ones === 1 ? "кредит" : ones >= 2 && ones <= 4 ? "кредити" : "кредитів";
  return `${n} ${word}`;
}

/** 47 → «0:47», 120 → «2:00». */
export function clock(seconds: number): string {
  const whole = Math.max(0, Math.round(seconds));
  return `${Math.floor(whole / 60)}:${String(whole % 60).padStart(2, "0")}`;
}

/** A wallet as a person recognises it, never whole: «F9pV…YPUv». */
export function shortWallet(wallet: string): string {
  return wallet.length > 10 ? `${wallet.slice(0, 4)}…${wallet.slice(-4)}` : wallet;
}

