/**
 * Metric definitions for the Admin — one registry the surfaces render from.
 *
 * Every number the admin draws has a definition here before it has a tile:
 * name, unit, source, counting rule, window, timezone, deduplication,
 * denominator, coverage and freshness. A tile without a definition is a
 * decoration, and the admin test refuses it.
 *
 * Units are deliberate. An account is an authenticated account; a login is one
 * confirmed server exchange; an event is one permitted action; a thread is one
 * support thread. Rows of notes are rows of notes, never people. Operator
 * accounts (the founder's own) are excluded from product metrics and reported
 * on their own line.
 */

