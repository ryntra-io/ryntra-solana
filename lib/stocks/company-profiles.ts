const key = (ticker: string): string => ticker.toUpperCase().replace(/\./g, "_");

/** The one line of what the company does, or what the fund holds, in the reader's language; null when this file names none. */
export function companyLine(ticker: string | null | undefined, lang: "en" | "uk"): string | null {
  if (!ticker) return null;
  const found = COMPANIES[key(ticker)] ?? FUNDS[key(ticker)];
  return found ? found[lang] : null;
}

/** A fund the issuers list by its ticker — SEC names only some of them, the catalogue names none as such. */
export function isKnownFund(ticker: string | null | undefined): boolean {
  return !!ticker && key(ticker) in FUNDS;
}
